// Run against npm run dev; PLAYWRIGHT_MODULE and CHROME_PATH select existing browser tooling.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const base = process.env.BASE_URL || "http://localhost:3000";
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(base);
    const canvas = page.getByRole("region", { name: "Visual Workflow Editor animated walkthrough" });
    await canvas.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelector('[data-step]')?.dataset.running === "true");
    assert.equal(await canvas.locator("video").count(), 0, "no video appears before generation");
    const initialHeight = await canvas.evaluate((node) => node.getBoundingClientRect().height);
    const wait = (step) => page.waitForFunction((value) => document.querySelector('[data-step]')?.dataset.step === String(value), step, { timeout: 12000 });
    assert.equal(await canvas.locator("input, textarea, select").count(), 0, "the walkthrough has no editable controls");
    assert.equal(await canvas.getByRole("button").count(), 1, "only the accessibility pause control is interactive");
    await wait(1);
    assert.equal(await canvas.locator('[data-library="tools"]').count(), 1, "toolbox opens automatically");
    await wait(3);
    assert.match(await canvas.locator('[data-anchor="note"]').textContent(), /Scene direction/);
    assert.equal(await canvas.locator('[data-panel="properties"]').count(), 1, "properties appear for a selected tool");
    await wait(6);
    assert.equal(await canvas.locator('[data-anchor="horse"]').getAttribute("data-highlight"), "true", "model choice is demonstrated");
    await canvas.screenshot({ path: `/tmp/canvas-models-${width}.png` });
    await wait(8);
    await canvas.getByRole("button", { name: "Pause canvas animation" }).click();
    await page.waitForTimeout(3100);
    assert.equal(await canvas.getAttribute("data-step"), "8", "pause freezes the walkthrough");
    await canvas.getByRole("button", { name: "Resume canvas animation" }).click();
    await wait(10);
    assert.equal(await canvas.locator('[data-anchor="option"]').count(), 1, "resolution options open automatically");
    await wait(11);
    assert.equal(await canvas.locator("video").count(), 0, "configuration never plays a result early");
    assert.equal(await canvas.locator('[data-anchor="generate"]').textContent(), "▷ Generate 2 takes");
    const generateBounds = await canvas.locator('[data-anchor="generate"]').boundingBox();
    const canvasBounds = await canvas.boundingBox();
    assert.ok(generateBounds.y + generateBounds.height < canvasBounds.y + canvasBounds.height - 45, "Generate stays inside the visible panel");
    await canvas.screenshot({ path: `/tmp/canvas-generate-${width}.png` });
    await wait(12);
    assert.equal(await canvas.locator("video").count(), 0, "generation precedes playback");
    assert.match(await canvas.locator('[data-anchor="model"]').textContent(), /Generating/);
    assert.equal(await canvas.locator('[data-panel="properties"]').count(), 0, "properties close to showcase results");
    await wait(13);
    await page.waitForFunction(() => { const videos = [...document.querySelectorAll('[data-step] video')]; return videos.length === 2 && videos.every(video => video.readyState >= 2 && !video.paused && !video.error); });
    const times = await canvas.locator('video').evaluateAll(videos => videos.map(video => video.currentTime));
    await page.waitForTimeout(300);
    const advanced = await canvas.locator('video').evaluateAll(videos => videos.map(video => video.currentTime));
    assert.ok(advanced.every((time, index) => time > times[index]), "both supplied videos actually play");
    await canvas.getByRole("button", { name: "Pause canvas animation" }).click();
    assert.equal(await canvas.locator('video').evaluateAll(videos => videos.every(video => video.paused)), true, "pause stops both videos");
    await canvas.getByRole("button", { name: "Resume canvas animation" }).click();
    assert.equal(await canvas.evaluate((node) => node.getBoundingClientRect().height), initialHeight, "scene changes keep the frame height stable");
    await canvas.screenshot({ path: `/tmp/canvas-properties-${width}.png` });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.waitForFunction(() => document.querySelector('[data-step]')?.dataset.running === "false");
    const stopped = await canvas.getAttribute("data-step");
    await page.waitForTimeout(1800);
    assert.equal(await canvas.getAttribute("data-step"), stopped, "offscreen animation stops");
    assert.equal(await canvas.locator("video").evaluateAll(videos => videos.length === 2 && videos.every(video => video.paused)), true, "offscreen videos pause too");
    await canvas.scrollIntoViewIfNeeded();
    await wait(0);
    assert.equal(await canvas.locator('[data-anchor="model"]').count(), 0, "loop resets cleanly");
    await page.emulateMedia({ reducedMotion: "reduce" });
    await canvas.scrollIntoViewIfNeeded();
    await wait(13);
    assert.equal(await canvas.locator("video").evaluateAll(videos => videos.length === 2 && videos.every(video => video.paused)), true, "reduced motion keeps static posters");
    assert.equal(await canvas.getAttribute("data-running"), "false", "reduced motion shows a static overview");
    assert.equal(await canvas.locator('[class*="cursor"]').evaluate((node) => getComputedStyle(node).display), "none");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "no horizontal overflow");
    assert.deepEqual(errors, [], "no browser errors");
    await page.close();
  }
  console.log("animated canvas: pass (desktop + mobile, autoplay, loop, pause, offscreen, reduced motion)");
} finally { await browser.close(); }
