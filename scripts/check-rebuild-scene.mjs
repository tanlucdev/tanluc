// Run with BASE_URL, PLAYWRIGHT_MODULE and optional CHROME_PATH; no added dependency.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.BASE_URL || "http://localhost:3000");
  const trigger = page.getByRole("button", { name: "Rebuild this scene" });
  const dialog = page.getByRole("dialog", { name: "Rebuilding the introductory scene" });
  await trigger.waitFor();
  await page.locator('[data-grass-ready="true"]').waitFor();
  const canvas = await page.locator(".meadow-tree-canvas").elementHandle();
  const navigation = page.getByRole("navigation", { name: "Main navigation" });
  const originalNavigation = await navigation.elementHandle();
  const navigationLinks = await navigation.locator("a").evaluateAll((elements) => elements.map((element) => element.getAttribute("href")));
  const checkRestored = async () => {
    await page.waitForFunction(() => !document.querySelector("dialog[open]"));
    assert.equal(await page.evaluate(() => document.documentElement.style.overflow), "");
    assert.equal(await page.locator(".meadow-hero").getAttribute("data-rebuilding"), null);
    assert.equal(await page.locator("#intro-title").evaluate((element) => getComputedStyle(element).opacity), "1");
    assert.equal(await page.locator(".meadow-scene").evaluate((element) => element.getAnimations({ subtree: true }).filter((animation) => animation.effect?.getKeyframes().some((frame) => "clipPath" in frame)).length), 0);
    assert(await canvas.evaluate((element) => element.isConnected), "Original canvas preserved");
    assert(await originalNavigation.evaluate((element) => element.isConnected), "Original navigation preserved");
    assert(await navigation.locator(":scope > a, li").evaluateAll((elements) => elements.every((element) => getComputedStyle(element).opacity === "1" && element.getAnimations().length === 0)), "Navigation restored after every exit");
    assert.deepEqual(await navigation.locator("a").evaluateAll((elements) => elements.map((element) => element.getAttribute("href"))), navigationLinks);
    assert(await page.locator(".meadow-token").evaluateAll((elements) => elements.every((element) => getComputedStyle(element).translate === "none" && getComputedStyle(element).rotate === "none" && element.getAnimations().length === 0)), "Icon positions restore after every exit");
    assert.equal(await page.locator("[data-terrain]").evaluate((element) => getComputedStyle(element).opacity), "0", "Terrain sketch clears after every exit");
  };
  await trigger.click();
  await dialog.waitFor();
  assert.equal(await page.locator("[data-rebuild-cursor]").count(), 5);
  assert.equal(await dialog.getByRole("status").textContent(), "5 agents building this scene…");
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector("#intro-title")).opacity) < 0.05);
  assert(await navigation.locator(":scope > a, li").evaluateAll((elements) => elements.length === 4 && elements.every((element) => Number(getComputedStyle(element).opacity) < 0.05)), "All navigation items join the rebuild");
  await page.keyboard.press("Escape");
  await checkRestored();
  assert(await trigger.evaluate((element) => document.activeElement === element), "Focus restored");
  await trigger.click();
  await page.waitForFunction(() => [...document.querySelectorAll("[data-rebuild-cursor]")].every((element) => Number(getComputedStyle(element).opacity) > 0.9));
  await page.waitForFunction(() => {
    const bounds = [...document.querySelectorAll(".meadow-token")].map((element) => element.getBoundingClientRect());
    return Math.max(...bounds.map((rect) => rect.left)) - Math.min(...bounds.map((rect) => rect.left)) < 32;
  });
  await page.screenshot({ path: "/tmp/rebuild-scene-icons-stack.png" });
  for (const name of ["Text", "Layout", "Tree", "Meadow", "Navigation"]) assert(await dialog.getByText(name, { exact: true }).isVisible());
  assert.equal(await page.locator(".meadow-actor--bike").evaluate((element) => getComputedStyle(element).opacity), "0", "Inactive actors stay hidden");
  await page.waitForFunction(() => {
    const title = document.querySelector("#intro-title");
    const text = document.querySelector(".meadow-hero__copy > p");
    return Number(getComputedStyle(title).opacity) === 1 && Number(getComputedStyle(text).opacity) === 1;
  });
  const typingFrames = await page.locator(".meadow-hero__copy > p").evaluate((element) => element.getAnimations().flatMap((animation) => animation.effect.getKeyframes()).filter((frame) => frame.clipPath?.startsWith("polygon")));
  assert(typingFrames.length > 40, "Text reveals measured characters, including wrapped lines");
  await page.waitForFunction(() => getComputedStyle(document.querySelector("[data-cursor-tool]")).opacity === "1");
  const clipping = await page.locator(".meadow-hero__copy > p").evaluate((element) => getComputedStyle(element).clipPath);
  assert(clipping.startsWith("polygon("), "Text reveals characters during typing instead of appearing at the end");
  await page.waitForFunction((previous) => getComputedStyle(document.querySelector(".meadow-hero__copy > p")).clipPath !== previous && getComputedStyle(document.querySelector("[data-cursor-tool]")).opacity === "1", clipping);
  assert(await dialog.locator("[data-rebuild-selection]").evaluateAll((elements) => elements.some((element) => element.getAnimations().length > 0)), "Object placement has synchronized selection frames");
  assert(await navigation.locator(":scope > a, li").evaluateAll((elements) => elements.every((element) => element.getAnimations().some((animation) => animation.effect.getKeyframes().some((frame) => frame.translate === "0px 6px" || frame.translate === "0 6px")))), "Navigation has its own baseline lettering treatment");
  assert(await dialog.locator('[data-rebuild-agent="Navigation"]').getByText("Navigation", { exact: true }).isVisible(), "Navigation has a dedicated agent");
  assert((await dialog.locator("[data-terrain] path").getAttribute("d")).includes(" Q"), "Terrain follows a curved sampled contour");
  await page.waitForFunction(() => {
    const path = document.querySelector("[data-terrain] path");
    const progress = parseFloat(getComputedStyle(path).strokeDashoffset);
    return progress > 0.05 && progress < 0.95 && Number(getComputedStyle(path.parentElement).opacity) > 0.5;
  });
  assert.equal(await dialog.locator("[data-terrain] circle").count(), 5);
  await page.screenshot({ path: "/tmp/rebuild-scene-progress.png" });
  await page.waitForFunction(() => /^[1-4] agents? building/.test(document.querySelector('[role="status"]').textContent));
  assert(await dialog.locator('[data-cursor-state="ready"]').evaluateAll((elements) => elements.some((element) => getComputedStyle(element).opacity === "1")), "Finished agents report Ready");
  assert(await dialog.locator("[data-rebuild-cursor]").evaluateAll((elements) => elements.every((element) => Number(getComputedStyle(element).opacity) > 0.9)), "Finished agents remain visible until everyone finishes");
  await dialog.getByRole("status").filter({ hasText: "Scene complete" }).waitFor();
  assert(await dialog.getByRole("button", { name: "Done" }).isVisible());
  assert(await dialog.locator("[data-rebuild-cursor]").evaluateAll((elements) => elements.every((element) => {
    const y = element.getBoundingClientRect().top;
    return y > innerHeight - 160 && y < innerHeight - 110;
  })), "Agents gather together at completion");
  await page.screenshot({ path: "/tmp/rebuild-scene-agents-ready.png" });
  assert(await navigation.locator(":scope > a, li").evaluateAll((elements) => elements.every((element) => getComputedStyle(element).opacity === "1")), "Navigation finishes with the scene");
  await checkRestored();
  await page.screenshot({ path: "/tmp/rebuild-scene-complete.png" });
  await trigger.click();
  await page.waitForFunction(() => [...document.querySelectorAll(".meadow-token")].some((element) => getComputedStyle(element).translate !== "none"));
  await dialog.getByRole("button", { name: "Skip" }).click();
  await checkRestored();
  await page.evaluate(() => window.scrollTo({ top: 120, behavior: "instant" }));
  await trigger.click();
  await page.keyboard.press("Escape");
  await checkRestored();
  assert.equal(await page.evaluate(() => window.scrollY), 120, "Scroll restored");
  await trigger.click();
  await page.setViewportSize({ width: 1300, height: 900 });
  await checkRestored();
  await trigger.click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await checkRestored();
  assert.equal(await trigger.isVisible(), false, "Reduced motion hides trigger");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await trigger.isVisible(), true, "Mobile exposes rebuild");
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth));
  await navigation.getByRole("link", { name: "About", exact: true }).click();
  await page.waitForURL((url) => url.pathname.replace(/\/$/, "") === "/about");
  await navigation.getByRole("link", { name: "Tan Luc", exact: true }).click();
  await page.waitForURL((url) => url.pathname === "/");
  await page.locator(".meadow-hero").waitFor();
  assert(await originalNavigation.evaluate((element) => element.isConnected), "Navigation still works without remounting");
  assert.deepEqual(errors, []);
  console.log("PASS: five simultaneous labeled agents, independent navigation lettering, working/completed status, reveal, auto completion, replay, Escape, Skip, focus, scroll, resize, reduced motion, mobile, original canvas, inactive actors, no runtime errors");
} finally {
  await browser.close();
}
